def sector_of_sic(sic) -> str:
    """SIC 코드를 한국어 업종명으로. 코드가 없으면 '기타'."""
    s = str(sic or '').strip()
    if not s or not s.isdigit():
        return '기타'
    s = s.zfill(4)
    return SIC3.get(s[:3]) or SIC2.get(s[:2]) or '기타'

