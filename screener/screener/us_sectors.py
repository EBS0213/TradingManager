def sector_of(sic, ticker=None) -> str:
    """
    업종 이름. **티커 손질표를 SIC 보다 먼저** 봅니다.

    ADR 은 SIC 가 아예 없고, SIC 가 있어도 지금 사업과 어긋나는 회사가
    있어서, 손으로 적은 표를 우선합니다.
    """
    t = str(ticker or '').strip().upper()
    if t and t in TICKER_FIX:
        return TICKER_FIX[t]
    return sector_of_sic(sic)


def big_of(sector) -> str:
    """세부 업종을 11갈래 대분류로. 히트맵의 큰 칸 이름입니다."""
    return BIG.get(str(sector or '').strip(), '기타')
