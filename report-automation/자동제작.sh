#!/bin/bash
# 사람이 없어도 도는 제작 스크립트. launchd 가 평일 12:30 에 부른다.
# 손으로 돌리는 '4_지금_보고서_만들기.command' 와 하는 일은 같고,
# 물어보지 않고(y 확인 없음) 끝에서 키를 기다리지 않는 것만 다르다.
cd "$(dirname "$0")" || exit 1
[ -f ./파이썬고르기.sh ] && . ./파이썬고르기.sh
mkdir -p 로그 report

for rc in "$HOME/.zprofile" "$HOME/.zshrc" "$HOME/.bash_profile" "$HOME/.profile"; do
  [ -r "$rc" ] && . "$rc" >/dev/null 2>&1
done
export PATH="$PATH:/usr/local/bin:/opt/homebrew/bin:$HOME/.local/bin:$HOME/.claude/local:$HOME/.npm-global/bin:$HOME/bin"

# 실제 실행기와 본인 로그인은 제작엔진/코덱스실행에서 확인합니다.

# 잠자기 방지 — 이 스크립트가 끝나면 자동으로 풀린다
command -v caffeinate >/dev/null 2>&1 && caffeinate -ims -w $$ &

echo "════════ 자동 제작 시작 $(date '+%F %T') ════════"

# 0) 홈페이지 워치리스트를 맥에 맞춘다 (2026-09-08 추가)
#    이것이 없으면 홈페이지에 새로 넣은 종목이 맥에서는 없는 것이 되어
#    자료수집도 보고서 제작도 대상에 들지 못한다. 실제로 셋이 어긋나 있었다.
#    --그대로 : 홈페이지에서 뺀 종목은 맥 CSV 에서도 뺀다. 자료·보고서 파일은 그대로 둔다.
echo "── 워치리스트 맞추기 ──"
if [ -f 워치리스트맞추기.py ]; then
  "$PY3" -u 워치리스트맞추기.py --그대로 2>&1 || echo "  (맞추기에 실패했습니다 — 있던 목록으로 그냥 갑니다)"
fi

# 1) 먼저 자료를 모은다. 수집이 안 된 종목은 보고서를 쓸 수 없다.
./알림.sh "자동 제작을 시작합니다" "자료를 모으고 밀린 보고서를 만듭니다" >/dev/null 2>&1
echo "── 수집 ──"
"$PY3" -u collect.py 2>&1 | tail -30

# 1-2) 셋업 있음 종목(2026-10-12부터, 예전엔 스카우트 80점) 중 자료가 없는 것을 따로 모은다
#   collect.py 는 워치리스트만 봅니다. 그런데 이제 제작 대상에 **당일 스카우트
#   80점 이상**이 들어오고, 그 종목들은 워치리스트에 없어 자료가 통째로 없습니다.
#   자료가 없으면 대상에 들어도 못 만들고 조용히 빠집니다 — 여기서 먼저 모읍니다.
#   (손으로 뺀 종목은 애초에 목록에 안 나오므로 헛수고하지 않습니다)
#   ※ 변수 이름을 영문으로 쓴 까닭 — 맥 기본 bash 는 3.2 라서 **한글 변수를 못 씁니다.**
#     `추가수집=...` 은 'command not found' 로 떨어지고 $추가수집 은 깨진 글자를 뱉습니다.
#     2026-09-28 에 실제로 이 블록이 통째로 안 돌았습니다 (`bash -n` 은 통과합니다).
#     브리핑발송.sh 가 같은 까닭으로 영문 변수를 씁니다.
EXTRA="$("$PY3" -u 종목고르기.py --수집대상 2>/dev/null | tr '\n' ' ')"
EXTRA="$(printf '%s' "$EXTRA" | tr -s ' ' | sed 's/^ *//; s/ *$//')"
if [ -n "$EXTRA" ]; then
  echo "── 스카우트 종목 수집 ── $EXTRA"
  # shellcheck disable=SC2086
  "$PY3" -u collect.py $EXTRA 2>&1 | tail -20
else
  echo "── 스카우트 종목 수집 ── 더 모을 것이 없습니다"
fi

# 2026-10-27: 자동 승인·수정 왕복 폐지. 완성본은 제작엔진에서 즉시 게시한다.

# 2) 만들 종목 고르기 — 보고서가 이미 있는 종목은 건너뛴다
echo "── 대상 고르기 ──"
rm -f 일시정지.flag
"$PY3" -u 종목고르기.py --auto
[ $? -eq 9 ] && { echo "만들 종목이 없습니다. 끝냅니다. $(date '+%F %T')"; exit 0; }

# 2.5) 고른 종목의 증권사 리포트를 받는다 (2026-10-04)
#   예전에는 아침 와이즈리포트 수집에 기대어 이 단계가 없었습니다. 와이즈가 끊기면서
#   네이버(로그인 없음)와 증권사 계정 수집으로 바꾸고, 고른 종목만 여기서 받습니다.
#   스카우트 종목은 워치리스트에 없어서 이렇게 해야 리포트가 들어옵니다.
#   못 받아도 제작은 갑니다 — 리포트는 읽는 재료일 뿐입니다.
echo "── 증권사 리포트 ──"
"$PY3" -u 네이버리포트받기.py --목록 제작목록.txt 2>&1 | tail -20 || true
if [ -f 증권사리포트받기.py ]; then
  "$PY3" -u 증권사리포트받기.py --목록 제작목록.txt 2>&1 | tail -20 || true
fi

# 3) 2개씩 동시에 (제작엔진.sh 가 실제 일을 한다)
. ./제작엔진.sh
run_all 제작목록.txt "${MAKE_JOBS:-2}"
echo "════════ 끝 $(date '+%F %T') ════════"
# 알림을 누르면 오늘 만든 보고서 폴더가 열립니다 (2026-09-05)
./알림.sh "자동 제작이 모두 끝났습니다" "앱의 「보고서 보기」에서 확인하세요" Glass "$(pwd)/report"
