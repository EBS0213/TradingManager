# 종성 ㅂ 의 자리번호. 「합·힙·됩·입」에서 이것을 떼면 「하·히·되·이」가 된다.
_종성ㅂ = 17


def 꼬리깎기(문장: str) -> str:
    """종결어미가 드러나도록 문장 끝의 군더더기를 걷어낸다.

    마침표·따옴표뿐 아니라 **끝에 달린 괄호**까지 떼야 한다.
    「…넘어섰습니다(코스피 기준).」 같은 문장이 흔한데, 괄호를 두면 맨끝이
    「기준」이 되어 평어체로 잘못 세어진다. 실제로 시황전략에서 22문장이 그랬다.
    """
    t = 문장.strip()
    for _ in range(3):                       # 괄호가 겹쳐 붙은 경우가 있다
        앞 = t
        t = t.rstrip('"\u201d\u2019\u300d\u300f .?!')
        t = re.sub(r"[(\uff08][^()\uff08\uff09]*[)\uff09]$", "", t).rstrip()
        if t == 앞:
            break
    return t.rstrip('"\u201d\u2019\u300d\u300f .?!')


def _앞말(t: str):
    """「니다/니까」를 뗀 앞말과, 그것이 진짜 습니다체인지를 돌려준다.

    하십시오체의 종결어미는 **-ㅂ니다 / -습니다** 뿐이다. 그래서 「니다」 앞 글자가
    `습` 이거나 **종성 ㅂ 을 이고 있어야** 한다. 이 조건을 빼면 평어체 「아니다」가
    습니다체로 잡힌다 — 실제로 첫 판에서 「분석이 아니다」가 통과로 세어졌다.
    """
    if not t.endswith(("니다", "니까")):
        return t, False
    앞 = t[:-2]
    if 앞.endswith("습"):                 # 그쳤습니다 → 그쳤
        return 앞[:-1], True
    if 앞:                                # 읽힙니다 → 읽히 · 입니다 → 이
        code = ord(앞[-1]) - 0xAC00
        if 0 <= code < 11172 and code % 28 == _종성ㅂ:
            return 앞[:-1] + chr(0xAC00 + code - _종성ㅂ), True
    return t, False                       # 아니다 · 지니다 — 평어체다


def 습니다체인가(문장: str) -> bool:
    return _앞말(꼬리깎기(문장))[1]


