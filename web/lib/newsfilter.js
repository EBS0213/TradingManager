/* ④ 아예 안 받는 언론사.
   · 머니투데이 (2026-08-23) — 한 시간에 수십 건을 밀어 넣는데 경제 RSS 인데도
     연예·스포츠·포토가 대부분입니다. 낱말로 걸러도 남는 것이 주제와 겉돕니다.
   여기에 이름을 적으면 뉴스 목록·종목별 뉴스·마감 브리핑에서 한꺼번에 빠집니다
   (셋 다 이 함수를 거쳐 간 결과를 씁니다). */
export const DROP_SOURCE = ['머니투데이']

/** 받을 언론사인가 — 받으면 true */
export function keepSource(source) {
  const s = String(source || '').replace(/\s/g, '')
  return !DROP_SOURCE.some((d) => s.includes(d.replace(/\s/g, '')))
}

/** 남길 기사인가 — 남기면 true */
export function keepArticle(title) {
  const t = decodeEntities(title)
  if (!t) return false
  if (TAG.test(t)) return false
  if (DROP.test(t) && !KEEP.test(t)) return false
  return true
}

/**
 * 목록에서 걸러내고, 제목의 실체 참조도 풀어 줍니다.
 *
 * 언론사 한 곳이 목록을 독차지하지 않도록 상한을 둡니다.
 * 기사를 자주 올리는 곳(머니투데이 등)은 몇 분 사이에 열 건씩 밀어 넣어서,
 * 그대로 두면 화면이 한 언론사로 도배됩니다. 시간순은 그대로 지키되
 * 한 곳이 perSource 건을 넘으면 그 뒤 기사는 건너뜁니다.
 */
export function filterNews(items, perSource = 10) {
  const out = []
  const n = {}
  for (const x of items || []) {
    if (!keepSource(x.source)) continue
    if (!keepArticle(x.title)) continue
    const src = String(x.source || '기타')
    n[src] = (n[src] || 0) + 1
    if (n[src] > perSource) continue
    out.push({ ...x, title: decodeEntities(x.title) })
  }
  return out
}
