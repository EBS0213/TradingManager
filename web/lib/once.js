const DONE = new Map()

export function once(key, fn) {
  return async (sql, ...rest) => {
    const got = DONE.get(key)
    if (got === true) return
    if (got) return got                    // 지금 누가 하고 있으면 같이 기다립니다
    const p = Promise.resolve(fn(sql, ...rest))
      .then(() => { DONE.set(key, true) })
      .catch((e) => { DONE.delete(key); throw e })
    DONE.set(key, p)
    return p
  }
}

/** 시험용 — 표시를 지웁니다 */
export function resetOnce(key) {
  if (key) DONE.delete(key); else DONE.clear()
}
